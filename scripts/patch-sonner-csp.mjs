/**
 * Extract sonner's runtime-injected CSS into a static file, and no-op
 * sonner's __insertCSS so CSP style-src-elem is not violated.
 *
 * Idempotent. Safe to run from postinstall / prebuild.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import crypto from "node:crypto";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const sonnerMjs = path.join(root, "node_modules/sonner/dist/index.mjs");
const sonnerCjs = path.join(root, "node_modules/sonner/dist/index.js");
const outCss = path.join(root, "src/styles/sonner-toast.css");

function extractCss(source) {
  const m = source.match(/__insertCSS\("((?:\\.|[^"\\])*)"\)/);
  if (!m) return null;
  return JSON.parse(`"${m[1]}"`);
}

function noOpInsertCss(source, label) {
  // Replace the function body with an immediate return, preserving the name
  // so sonner's call site still works.
  const next = source.replace(
    /function __insertCSS\(code\) \{[\s\S]*?\n\}/,
    `function __insertCSS(code) {\n  // MedVerse CSP: styles live in src/styles/sonner-toast.css (style-src 'self').\n  return;\n}`
  );
  if (next === source) {
    // Already patched, or unexpected format
    if (source.includes("MedVerse CSP: styles live in src/styles/sonner-toast.css")) {
      return { patched: false, already: true };
    }
    throw new Error(`failed to patch __insertCSS in ${label}`);
  }
  return { patched: true, already: false, next };
}

if (!fs.existsSync(sonnerMjs)) {
  console.warn("patch-sonner-csp: sonner not installed; skip");
  process.exit(0);
}

const mjs = fs.readFileSync(sonnerMjs, "utf8");
const css = extractCss(mjs);
if (!css) {
  // After patch, the CSS string may still exist as dead code, or already extracted.
  if (fs.existsSync(outCss)) {
    console.log("patch-sonner-csp: css present; insertCSS check…");
  } else {
    throw new Error("could not extract sonner CSS (__insertCSS string missing)");
  }
} else {
  const hash = crypto.createHash("sha256").update(css, "utf8").digest("base64");
  const header =
    `/* Auto-extracted from sonner runtime __insertCSS (sha256=${hash}).\n` +
    ` * Served as a static stylesheet so CSP style-src-elem does not need unsafe-inline.\n` +
    ` * Regenerated by scripts/patch-sonner-csp.mjs\n */\n`;
  fs.mkdirSync(path.dirname(outCss), { recursive: true });
  fs.writeFileSync(outCss, header + css + "\n");
  console.log(`patch-sonner-csp: wrote ${outCss} (${css.length} bytes, sha256=${hash})`);
}

for (const [file, label] of [
  [sonnerMjs, "index.mjs"],
  [sonnerCjs, "index.js"],
]) {
  if (!fs.existsSync(file)) continue;
  const src = fs.readFileSync(file, "utf8");
  const result = noOpInsertCss(src, label);
  if (result.already) {
    console.log(`patch-sonner-csp: ${label} already patched`);
  } else if (result.patched) {
    fs.writeFileSync(file, result.next);
    console.log(`patch-sonner-csp: patched ${label}`);
  }
}
